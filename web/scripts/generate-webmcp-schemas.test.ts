import { describe, expect, test } from 'bun:test';
import {
	generateModule,
	operationInputSchema,
	type Spec,
} from './generate-webmcp-schemas.ts';

const spec: Spec = {
	paths: {
		'/api/things/{thingId}': {
			parameters: [
				{
					name: 'thingId',
					in: 'path',
					required: true,
					schema: { type: 'string' },
				},
			],
			get: {
				operationId: 'getThing',
				parameters: [
					{ $ref: '#/components/parameters/Kind' },
					{
						name: 'limit',
						in: 'query',
						required: false,
						description: 'Max items.\n',
						schema: { type: 'integer', minimum: 1 },
					},
					{ name: 'X-Trace', in: 'header', schema: { type: 'string' } },
				],
			},
		},
		'/api/plain': { get: { operationId: 'getPlain' } },
	},
	components: {
		parameters: {
			Kind: {
				name: 'kind',
				in: 'query',
				required: true,
				description: 'Which kind.',
				schema: { $ref: '#/components/schemas/KindName' },
			},
		},
		schemas: { KindName: { type: 'string', enum: ['a', 'b'] } },
	},
};

describe('operationInputSchema', () => {
	test('turns path and query parameters into properties, following $ref', () => {
		expect(operationInputSchema(spec, 'getThing')).toEqual({
			type: 'object',
			properties: {
				thingId: { type: 'string' },
				kind: { type: 'string', enum: ['a', 'b'], description: 'Which kind.' },
				limit: { type: 'integer', minimum: 1, description: 'Max items.' },
			},
			required: ['thingId', 'kind'],
			additionalProperties: false,
		});
	});

	test('leaves header parameters out, since auth is not a tool input', () => {
		const schema = operationInputSchema(spec, 'getThing');

		expect(Object.keys(schema.properties)).not.toContain('X-Trace');
	});

	test('an operation with no parameters has an empty object schema', () => {
		expect(operationInputSchema(spec, 'getPlain')).toEqual({
			type: 'object',
			properties: {},
			required: [],
			additionalProperties: false,
		});
	});

	test('an unknown operation is an error naming it', () => {
		expect(() => operationInputSchema(spec, 'nope')).toThrow('nope');
	});

	test('applies an override to a property the operation has', () => {
		const schema = operationInputSchema(spec, 'getThing', {
			limit: { default: 20, description: 'Defaults to 20.' },
		});

		expect(schema.properties.limit).toEqual({
			type: 'integer',
			minimum: 1,
			default: 20,
			description: 'Defaults to 20.',
		});
	});

	test('an override for a property the spec lacks is an error', () => {
		expect(() =>
			operationInputSchema(spec, 'getThing', {
				gone: { default: 1, description: 'x' },
			}),
		).toThrow('gone');
	});
});

describe('generateModule', () => {
	test('exports one schema per tool, keyed by tool name', () => {
		const source = generateModule(spec, { get_thing: 'getThing' }, {});

		expect(source).toContain('export const inputSchemas');
		expect(source).toContain('"get_thing"');
		expect(source).toContain('Generated by scripts/generate-webmcp-schemas.ts');
	});
});

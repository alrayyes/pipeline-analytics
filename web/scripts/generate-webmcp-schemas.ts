// Writes src/lib/webmcpSchemas.generated.ts: each WebMCP tool's JSON Schema
// input, built from the parameters of the OpenAPI operation the tool wraps
// (#649, rules/mcp.md), so a schema is never a hand-copy that drifts. The output
// is committed, and webmcpSchemas.test.ts regenerates it in memory and fails
// when the committed file is stale -- a changed spec parameter turns that test
// red until `bun scripts/generate-webmcp-schemas.ts` has been run.

import { join } from 'node:path';
import {
	toolOperations,
	toolParameterOverrides,
} from '../src/lib/webmcpOperations.ts';

type Json = Record<string, unknown>;

type Parameter = {
	$ref?: string;
	name?: string;
	in?: string;
	required?: boolean;
	description?: string;
	schema?: Json;
};

type Operation = { operationId: string; parameters?: Parameter[] };

export type Spec = {
	paths: Record<string, Json>;
	components?: { parameters?: Record<string, Parameter>; schemas?: Json };
};

export type InputSchema = {
	type: 'object';
	properties: Record<string, Json>;
	required: string[];
	additionalProperties: false;
};

export type Overrides = Record<string, Json>;

const methods = ['get', 'post', 'put', 'patch', 'delete'];

// Follows a local `#/...` reference, wherever it points in the document.
function resolve<T>(spec: Spec, node: T): T {
	const ref = (node as { $ref?: string } | undefined)?.$ref;
	if (ref === undefined) return node;

	let target: unknown = spec;
	for (const key of ref.replace(/^#\//, '').split('/')) {
		target = (target as Json)[key];
	}

	return resolve(spec, target as T);
}

// A schema with every nested $ref inlined, so a tool's schema stands alone.
function inline(spec: Spec, schema: unknown): unknown {
	if (Array.isArray(schema)) return schema.map((item) => inline(spec, item));
	if (typeof schema !== 'object' || schema === null) return schema;

	const resolved = resolve(spec, schema as Json);

	return Object.fromEntries(
		Object.entries(resolved).map(([key, value]) => [key, inline(spec, value)]),
	);
}

function findOperation(spec: Spec, operationId: string) {
	for (const item of Object.values(spec.paths)) {
		for (const method of methods) {
			const operation = item[method] as Operation | undefined;
			if (operation?.operationId === operationId) {
				return {
					operation,
					shared: (item.parameters as Parameter[] | undefined) ?? [],
				};
			}
		}
	}

	throw new Error(`openapi.yaml has no operation ${operationId}`);
}

export function operationInputSchema(
	spec: Spec,
	operationId: string,
	overrides: Overrides = {},
): InputSchema {
	const { operation, shared } = findOperation(spec, operationId);
	const properties: Record<string, Json> = {};
	const required: string[] = [];

	for (const ref of [...shared, ...(operation.parameters ?? [])]) {
		const param = resolve(spec, ref);
		if (param.in !== 'path' && param.in !== 'query') continue;

		const name = param.name as string;
		const description = param.description?.trim();
		properties[name] = {
			...(inline(spec, param.schema) as Json),
			...(description ? { description } : {}),
		};
		if (param.required) required.push(name);
	}

	for (const [name, override] of Object.entries(overrides)) {
		if (!(name in properties)) {
			throw new Error(`${operationId} has no parameter ${name} to override`);
		}
		properties[name] = { ...properties[name], ...(override as Json) };
	}

	return { type: 'object', properties, required, additionalProperties: false };
}

export function generateModule(
	spec: Spec,
	tools: Record<string, string>,
	overrides: Record<string, Overrides>,
): string {
	const schemas = Object.fromEntries(
		Object.entries(tools).map(([tool, operationId]) => [
			tool,
			operationInputSchema(spec, operationId, overrides[tool]),
		]),
	);

	return `// Generated by scripts/generate-webmcp-schemas.ts from openapi/openapi.yaml.
// Do not edit by hand; run \`bun scripts/generate-webmcp-schemas.ts\`.

export const inputSchemas = ${JSON.stringify(schemas, null, '\t')} as const;
`;
}

export async function loadSpec(): Promise<Spec> {
	const text = await Bun.file(
		new URL('../../openapi/openapi.yaml', import.meta.url),
	).text();

	return Bun.YAML.parse(text) as Spec;
}

if (import.meta.main) {
	const output = join(
		import.meta.dir,
		'..',
		'src',
		'lib',
		'webmcpSchemas.generated.ts',
	);
	await Bun.write(
		output,
		generateModule(await loadSpec(), toolOperations, toolParameterOverrides),
	);
}
